create or replace function public.review_court_request(
  request_id bigint,
  new_status text
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  requested public.court_requests%rowtype;
  new_facility_id bigint;
begin
  if not (select public.is_admin()) then
    raise exception 'Only administrators can review court requests';
  end if;
  if new_status not in ('Confirmed', 'Rejected') then
    raise exception 'Invalid court request status';
  end if;

  select * into requested
  from public.court_requests
  where id = request_id and status = 'Pending'
  for update;

  if not found then
    raise exception 'Pending court request not found';
  end if;

  if new_status = 'Confirmed' then
    insert into public.facilities (
      owner_id, source_request_id, name, type, location, price, image, description
    )
    values (
      requested.requester_id,
      requested.id,
      requested.name,
      requested.type,
      requested.location,
      requested.price,
      requested.image,
      requested.description
    )
    returning id into new_facility_id;
  end if;

  update public.court_requests
  set status = new_status
  where id = request_id;

  return new_facility_id;
end;
$$;

grant execute on function public.review_court_request(bigint, text) to authenticated;

create or replace function public.register_for_event(
  requested_event_id bigint,
  requested_spots integer
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  event_record public.events%rowtype;
  registration_id bigint;
begin
  if auth.uid() is null or requested_spots < 1 then
    raise exception 'A signed-in user and valid spot count are required';
  end if;

  select * into event_record
  from public.events
  where id = requested_event_id
  for update;

  if not found or event_record.spots_left < requested_spots then
    raise exception 'There are not enough spots available';
  end if;

  if exists (
    select 1 from public.event_registrations
    where event_id = requested_event_id and user_id = auth.uid()
  ) then
    raise exception 'You already have a registration for this event';
  end if;

  insert into public.event_registrations (event_id, user_id, spots)
  values (requested_event_id, auth.uid(), requested_spots)
  returning id into registration_id;

  update public.events
  set spots_left = spots_left - requested_spots
  where id = requested_event_id;

  return registration_id;
end;
$$;

create or replace function public.review_event_registration(
  registration_id bigint,
  new_status text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  registration public.event_registrations%rowtype;
begin
  if not (select public.is_admin()) then
    raise exception 'Only administrators can review registrations';
  end if;
  if new_status not in ('Confirmed', 'Rejected') then
    raise exception 'Invalid registration status';
  end if;

  select * into registration
  from public.event_registrations
  where id = registration_id and status = 'Pending'
  for update;

  if not found then
    raise exception 'Pending registration not found';
  end if;

  update public.event_registrations
  set status = new_status
  where id = registration_id;

  if new_status = 'Rejected' then
    update public.events
    set spots_left = least(capacity, spots_left + registration.spots)
    where id = registration.event_id;
  end if;
end;
$$;

create or replace function public.cancel_event_registration(registration_id bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  registration public.event_registrations%rowtype;
begin
  select * into registration
  from public.event_registrations
  where id = registration_id
    and user_id = auth.uid()
    and status = 'Pending'
  for update;

  if not found then
    raise exception 'Pending registration not found';
  end if;

  delete from public.event_registrations where id = registration_id;
  update public.events
  set spots_left = least(capacity, spots_left + registration.spots)
  where id = registration.event_id;
end;
$$;

